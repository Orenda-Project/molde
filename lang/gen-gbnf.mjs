#!/usr/bin/env node
// Generates lang/moldescript.gbnf (llama.cpp GBNF) from lang/grammar/moldescript.grammar.
// Usage: node lang/gen-gbnf.mjs            (writes the file)
//        node lang/gen-gbnf.mjs --check    (exit 1 if the file is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { readRules, loadGrammar, literals } from './grammar.mjs';

export const MAX_DEPTH = 8;
const here = dirname(fileURLToPath(import.meta.url));
export const GBNF_PATH = join(here, 'moldescript.gbnf');
export const TOKENS_PATH = join(here, 'grammar', 'added-tokens.json');

// The single tokens we plan to add to the model's tokenizer: every grammar literal, the
// standard component names, and one token per indentation depth.
export async function addedTokens() {
  const { stdDefs } = await import('./expand.mjs');
  const lits = literals(loadGrammar()).filter(l => l !== ' ');
  const std = [...stdDefs().keys()];
  const indents = Array.from({ length: MAX_DEPTH }, (_, d) => '  '.repeat(d + 1));
  return { note: 'generated by lang/gen-gbnf.mjs', literals: lits.sort(), std: std.sort(), indents };
}

export function generate() {
  loadGrammar(); // validates
  const rules = readRules();
  const out = [
    '# GENERATED by lang/gen-gbnf.mjs from lang/grammar/moldescript.grammar. Do not edit.',
    '# MoldeScript v0: a program is an ask line, or an app line followed by statements.',
    '# Children of a block statement are indented two more spaces (depth limit ' + MAX_DEPTH + ').',
    'root ::= ask-stmt nl | app-stmt nl blk0',
    'nl ::= "\\n"',
    'blk0 ::= ( block-stmt nl blk1? | leaf-stmt nl )*',
  ];
  for (let d = 1; d <= MAX_DEPTH; d++) {
    const ind = JSON.stringify('  '.repeat(d));
    const deeper = d < MAX_DEPTH ? ` blk${d + 1}?` : '';
    out.push(`blk${d} ::= ( ${ind} block-stmt nl${deeper} | ${ind} leaf-stmt nl )+`);
  }
  for (const r of rules) {
    if (r.name === 'lib-first' || r.name === 'first-stmt') continue; // parser-only entry points
    out.push(`${r.name} ::= ${r.body}`);
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const cur = existsSync(GBNF_PATH) ? readFileSync(GBNF_PATH, 'utf8') : '';
    if (cur !== text) { console.error('moldescript.gbnf is stale: run node lang/gen-gbnf.mjs'); process.exit(1); }
    console.log('moldescript.gbnf is up to date');
  } else {
    writeFileSync(GBNF_PATH, text);
    const t = await addedTokens();
    writeFileSync(TOKENS_PATH, JSON.stringify(t, null, 1) + '\n');
    console.log('wrote ' + TOKENS_PATH + ' (' + (t.literals.length + t.std.length + t.indents.length) + ' tokens)');
    console.log('wrote ' + GBNF_PATH + ' (' + text.split('\n').length + ' lines)');
  }
}

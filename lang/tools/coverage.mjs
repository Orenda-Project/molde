// Builds lang/corpus/COVERAGE.md from corpus/requests.jsonl and corpus/coverage-results.jsonl
// (the round-1 blind coverage test: three agents wrote one program per request from SPEC.md and
// judged each as full, partial or no). Usage: node lang/tools/coverage.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const D = join(dirname(fileURLToPath(import.meta.url)), '..', 'corpus');
const rd = f => readFileSync(join(D, f), 'utf8').split('\n').filter(Boolean).map(l => JSON.parse(l));
const req = new Map(rd('requests.jsonl').map(r => [r.id, r]));
const res = rd('coverage-results.jsonl');
const count = (xs, f) => xs.reduce((m, x) => (m[f(x)] = (m[f(x)] || 0) + 1, m), {});
const v = count(res, r => r.verdict);
const inScope = res.filter(r => r.missing !== 'outside_world');
const full = x => x.filter(r => r.verdict === 'full').length;
// language gaps reported in round 1, and what round 3 did about each
const FIXED = [
  [/before|offset|computed date|minus N days/i, 'remind at T.field - 3d at 9:00 (round 2)'],
  [/day of month|monthly|recurring/i, 'remind ... monthly on 1 at 9:00 (round 2)'],
  [/join|plan -> dish/i, 'group by a field through links: by dish.cuisine (round 2)'],
  [/sort by a formula|aggregate/i, 'sort FORMULA (round 2)'],
  [/colour|color/i, 'named colours and hue() (round 2)'],
  [/random/i, 'random() inside actions, random(table), shuffle (rounds 2 and 3)'],
  [/minute/i, 'minute(), second(), month(), year() (round 2)'],
  [/condition/i, 'remind ... if condition, when (round 1); due() (round 3)'],
];
const out = [];
out.push('# Coverage of the 300 blind requests (round 1)', '');
out.push('Generated by `node lang/tools/coverage.mjs` from `requests.jsonl` (the 300 English requests) and `coverage-results.jsonl` (one verdict per request from the three agents who wrote the programs in this folder from SPEC.md, round-1 language). The programs here are those agents\' programs, migrated to the current spelling with `mo.mjs migrate`.', '');
out.push(`All ${res.length} programs passed the checker when written (they still do: see tests/corpus.test.mjs).`, '');
out.push('| verdict | count |', '|---|---:|');
for (const k of ['full', 'partial', 'no']) out.push(`| ${k} | ${v[k] || 0} |`);
out.push('', `Requests that need the outside world (messaging, sync, camera, maps, network, print): ${res.length - inScope.length}. Of the ${inScope.length} in-scope requests, ${full(inScope)} are full (${Math.round(full(inScope) * 1000 / inScope.length) / 10}%). Overall full: ${full(res)} of ${res.length} (${Math.round(full(res) * 1000 / res.length) / 10}%). The gate (90% expressible) counts in-scope requests.`, '');
out.push('## By request style', '', '| style | n | full | partial | no |', '|---|---:|---:|---:|---:|');
const byStyle = {};
for (const r of res) { const st = req.get(r.id)?.style || '?'; (byStyle[st] ||= { n: 0, full: 0, partial: 0, no: 0 }); byStyle[st].n++; byStyle[st][r.verdict]++; }
for (const [st, c] of Object.entries(byStyle).sort()) out.push(`| ${st} | ${c.n} | ${c.full} | ${c.partial} | ${c.no} |`);
out.push('', '## Why requests were partial or not covered', '', '| kind | count |', '|---|---:|');
for (const [k, n] of Object.entries(count(res.filter(r => r.verdict !== 'full'), r => r.missing)).sort((a, b) => b[1] - a[1])) out.push(`| ${k} | ${n} |`);
out.push('', '## Language gaps reported, and what was done', '', '| request | gap | status now |', '|---|---|---|');
for (const r of res.filter(r => r.missing === 'language_feature')) {
  const fix = FIXED.find(([re]) => re.test(r.missing_detail || ''));
  out.push(`| ${r.id} | ${(r.missing_detail || '').replace(/\|/g, '/')} | ${fix ? 'added: ' + fix[1] : 'still out of scope (see README)'} |`);
}
out.push('', '## Every request', '', '| id | style | verdict | request | reason |', '|---|---|---|---|---|');
for (const r of res) { const q = req.get(r.id); out.push(`| ${r.id} | ${q?.style || ''} | ${r.verdict} | ${(q?.text || '').replace(/\|/g, '/').replace(/\n/g, ' ')} | ${(r.reason || '').replace(/\|/g, '/')} |`); }
writeFileSync(join(D, 'COVERAGE.md'), out.join('\n') + '\n');
console.log(`wrote corpus/COVERAGE.md: ${res.length} results, full ${v.full}, partial ${v.partial}, no ${v.no}`);
